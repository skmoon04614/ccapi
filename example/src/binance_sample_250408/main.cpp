  explicit Binance(std::string apiKey = "", std::string apiSecret = "")
      : sessionConfigs([&]() {
          ::ccapi::SessionConfigs temp;
          if (apiKey.empty()) {
            apiKey = ::ccapi::UtilSystem::getEnvAsString("BINANCE_API_KEY");
          }

          if (apiSecret.empty()) {
            apiSecret = ::ccapi::UtilSystem::getEnvAsString("BINANCE_API_SECRET");
          }

          temp.setCredential({
              {"BINANCE_API_KEY", apiKey},
              {"BINANCE_API_SECRET", apiSecret},
          });
          return temp;
        }()),
        session(sessionOptions, sessionConfigs) {}

  ~Binance() { session.stop(); }

  ::ccapi::Event fetchOrderBook(const std::string& symbol, int limit = 20) {
    if (limit <= 5) {
      limit = 5;
    } else if (limit <= 10) {
      limit = 10;
    } else if (limit <= 20) {
      limit = 20;
    } else if (limit <= 50) {
      limit = 50;
    } else if (limit <= 100) {
      limit = 100;
    } else if (limit <= 500) {
      limit = 500;
    } else if (limit <= 1000) {
      limit = 1000;
    } else {
      limit = 5000;
    }

    std::string endpoint = "/api/v3/depth";
    const std::string marketType = getMarketTypeBySymbol(symbol);
    if (marketType == "usdt_m") {
      endpoint = "/fapi/v1/depth";
    } else if (marketType == "coin_m") {
      endpoint = "/dapi/v1/depth";
    } else if (marketType == "option") {
      endpoint = "/vapi/v1/depth";
    }

    ::ccapi::Request request(::ccapi::Request::Operation::GENERIC_PUBLIC_REQUEST, exchange(marketType));
    request.appendParam({
        {"HTTP_METHOD", "GET"},
        {"HTTP_PATH", endpoint},
        {"HTTP_QUERY_STRING", "symbol=" + getRawSymbol(symbol) + "&limit=" + std::to_string(limit)},
    });
    session.sendRequest(request, &eventQueue);
    return eventQueue.purge()[0];
  }

  ::ccapi::Event cancelOrder(const std::string& symbol, const unsigned int& orderId) {
    ::ccapi::Request request(::ccapi::Request::Operation::CANCEL_ORDER, exchange(getMarketTypeBySymbol(symbol)), getRawSymbol(symbol));
    request.appendParam({
        {"recvWindow", "60000"},
        {"orderId", std::to_string(orderId)},
    });
    session.sendRequest(request, &eventQueue);
    return eventQueue.purge()[0];
  }

  static std::string getMarketTypeBySymbol(const std::string& symbol) {
    if (symbol.find('/') != std::string::npos) {
      return "spot";
    }

    const std::vector<std::string> tokens = str_util::split(symbol, '-');
    if (tokens.size() < 2) {
      throw std::runtime_error("Invalid symbol: " + symbol);
    }

    const std::string last = str_util::toUpper(tokens.back());
    if (last == "C" || last == "F") {  // Call or Foot options
      return "option";
    }

    if (str_util::isDigit(last) || last == "SWAP" || last == "THIS" || last == "NEXT" || last == "THISM" || last == "NEXTM" || last == "Q" || last == "BIQ") {
      const std::string second = tokens[1];
      if (second == "USDT" || second == "BTC") {
        return "usdt_m";
      }

      if (second == "USD") {
        return "coin_m";
      }
    }

    throw std::runtime_error("Invalid symbol: " + symbol);
  }

